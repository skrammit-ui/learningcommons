#!/usr/bin/env python3
"""Generate a fictional Grade 4 class CSV (cluster scores, 0-100) for trying the app."""

import csv
import json
import os
import random

random.seed(7)

CLUSTERS = ["4.OA.A", "4.OA.B", "4.NBT.A", "4.NBT.B", "4.NF.A", "4.NF.B", "4.NF.C", "4.MD.A", "4.G.A"]

# Learner profiles: mean score per cluster. Students get noise around one profile.
PROFILES = {
    "strong": dict.fromkeys(CLUSTERS, 88),
    "fractions": {**dict.fromkeys(CLUSTERS, 78), "4.NF.A": 48, "4.NF.B": 42, "4.NF.C": 50},
    "place_value": {**dict.fromkeys(CLUSTERS, 74), "4.NBT.A": 45, "4.NBT.B": 40, "4.OA.A": 58, "4.MD.A": 60},
    "broad_support": {**dict.fromkeys(CLUSTERS, 45), "4.G.A": 62, "4.OA.B": 55},
}
COUNTS = {"strong": 7, "fractions": 8, "place_value": 6, "broad_support": 5}

FIRST = ["Ava", "Mateo", "Zoe", "Liam", "Priya", "Noah", "Amara", "Ethan", "Sofia", "Kai", "Lena", "Omar",
         "Hana", "Diego", "Maya", "Jonah", "Imani", "Leo", "Nora", "Theo", "Aisha", "Ben", "Rosa", "Felix",
         "Mila", "Samir"]
LAST = "ABCDEFGHJKLMNPRSTVWZ"


def main():
    out = os.path.join(os.path.dirname(__file__), "..", "sample-data", "grade4-cluster-scores.csv")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    rows = []
    names = iter(FIRST)
    for profile, n in COUNTS.items():
        for _ in range(n):
            name = f"{next(names)} {random.choice(LAST)}."
            row = {"Student": name}
            for c in CLUSTERS:
                v = random.gauss(PROFILES[profile][c], 8)
                row[c] = int(max(0, min(100, round(v))))
            rows.append(row)
    random.shuffle(rows)
    # Leave a couple of blanks, as real exports often have them.
    rows[3]["4.G.A"] = ""
    rows[11]["4.MD.A"] = ""
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["Student"] + CLUSTERS)
        w.writeheader()
        w.writerows(rows)
    # Same data as a script, so the "Try sample" button works when index.html is opened from disk.
    with open(out) as f:
        text = f.read()
    with open(out[:-4] + ".js", "w") as f:
        f.write("// Generated by app/tools/make_sample_csv.py. Fictional students.\n")
        f.write(f"window.SAMPLE_CSV = {json.dumps(text)};\n")
    print(f"wrote {os.path.abspath(out)} ({len(rows)} students)")


if __name__ == "__main__":
    main()
